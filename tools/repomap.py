"""Writes docs/REPOMAP.md: a short index of every Lua file (what it is for, its sections, its functions and the line
each starts on), so an agent can read the map once and then open only the lines it needs instead of whole files.

Usage: python tools/repomap.py           rewrite docs/REPOMAP.md
       python tools/repomap.py --check   exit 1 if docs/REPOMAP.md is out of date (writes nothing)

tools/prereview.py rewrites the map on every run, so it stays current without anyone remembering to.
Reads the add-on's own conventions: a comment block at the top of each file, `-----` banner lines around a section
name, and `function X.Name(` / `local function Name(` declarations. Nothing else in the file is parsed.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "REPOMAP.md"
BANNER = re.compile(r"^-{20,}\s*$")
FUNC = [
    re.compile(r"^\s*function\s+([A-Za-z_][\w.:]*)\s*\("),
    re.compile(r"^\s*local\s+function\s+([A-Za-z_]\w*)\s*\("),
    re.compile(r"^\s*([A-Za-z_][\w.]*)\s*=\s*function\s*\("),
]
HEADER = (
    "# Repo map\n\n"
    "Generated by `python tools/repomap.py` (also run by `tools/prereview.py`); do not edit by hand.\n"
    "Read this first, then open only the lines you need. `L123` is the line a section or function starts on;\n"
    "names with a dot or colon (`F.Layout`) are shared with other files, bare names are local to the file.\n"
    "Load order is the `.toc` order below.\n"
)


def toc_order():
    toc = (ROOT / "CleanQuestTracker.toc").read_text(encoding="utf-8").splitlines()
    return [line.strip().replace("\\", "/") for line in toc if line.strip().endswith(".lua")]


def purpose(lines):
    """The file's opening comment block, flattened to one line and cut to a sensible length."""
    parts = []
    for line in lines:
        if not line.startswith("--"):
            break
        text = line.lstrip("-").strip()
        if text:
            parts.append(text)
    text = " ".join(parts)
    if text.startswith("Clean Quest Tracker:"):
        text = text[len("Clean Quest Tracker:"):].strip()
    return text if len(text) <= 260 else text[:257].rsplit(" ", 1)[0] + "..."


def scan(lines):
    """[(section name, start line, [function names])]; functions before any banner go in a section called '(top)'."""
    sections = [["(top)", 1, []]]
    i = 0
    while i < len(lines):
        line = lines[i]
        if BANNER.match(line) and i + 2 < len(lines) and lines[i + 1].startswith("-- ") and BANNER.match(lines[i + 2]):
            sections.append([lines[i + 1][3:].strip(), i + 1, []])
            i += 3
            continue
        for pattern in FUNC:
            match = pattern.match(line)
            if match:
                name = match.group(1)
                # Only top-level declarations; nested helpers inside a function are indented further than one tab.
                if len(line) - len(line.lstrip("\t")) <= 1:
                    sections[-1][2].append(f"{name} L{i + 1}")
                break
        i += 1
    return [s for s in sections if s[2] or s[0] != "(top)"]


def build():
    out = [HEADER]
    for name in toc_order():
        path = ROOT / name
        if not path.exists():
            continue
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        out.append(f"## {name} ({len(lines)} lines)\n")
        text = purpose(lines)
        if text:
            out.append(text + "\n")
        for title, start, funcs in scan(lines):
            if funcs:
                out.append(f"- **{title}** L{start}: " + ", ".join(funcs))
            else:
                out.append(f"- **{title}** L{start}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/REPOMAP.md is out of date: run python tools/repomap.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines, {len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
